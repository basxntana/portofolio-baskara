"""
Authors the character sprites as segment lists and emits TypeScript.

Writing pixel rows as (char, count) segments instead of literal strings means a
row's width is computed, never counted by hand -- the assert catches any row
that does not add up before it reaches the browser.

Run:  python3 scripts/build-sprites.py
"""

from pathlib import Path

OUT = Path("src/components/pixel/characters.ts")


def grid(width, rows):
    out = []
    for i, segs in enumerate(rows):
        line = "".join(ch * n for ch, n in segs)
        assert len(line) == width, (
            f"row {i} is {len(line)} px wide, expected {width}: {line!r}"
        )
        out.append(line)
    return out


